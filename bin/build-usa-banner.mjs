// Compiles the USWDS banner to plain CSS for the theme.
//
//   node bin/build-usa-banner.mjs            write styles/_usa-banner-generated.scss
//   node bin/build-usa-banner.mjs --check    exit 1 when the committed file is stale
//
// Why a separate step: rollup-plugin-sass bundles Dart Sass 1.66, which cannot read
// the USWDS 3.14 sources, and compiling the whole theme with the repo's newer Sass
// changes how declarations after a nested @include are ordered (Sass 1.77.7), which
// flips the theme's responsive overrides. So only the banner is compiled here, with
// the repo's own Sass, and the theme imports the result as plain CSS.
//
// Only the banner, the accordion base it uses and the media block are built, from each
// package's `src/styles` so their @font-face rules are not emitted. That keeps every
// selector class-scoped: no reset, grid, utility or element rule reaches the page.
// The order matters: the banner overrides accordion rules of equal specificity, as it
// does in the full USWDS build (accordion, then banner).
import fs from "node:fs";
import path from "node:path";
import * as sass from "sass";

const uswdsRoot = path.resolve("node_modules/@uswds/uswds");
const uswdsVersion = JSON.parse(
  fs.readFileSync(path.join(uswdsRoot, "package.json"), "utf-8")
).version;
const OUTPUT = path.resolve("styles/_usa-banner-generated.scss");

// USWDS system colors the banner uses, mapped onto NEXUS role tokens so the theme
// keeps one source of color. A color that is not listed fails the build: a USWDS
// update that introduces one needs a mapping decision.
const COLOR_TOKENS = new Map([
  ["#f0f0f0", "var(--surface-subtle)"],
  ["#dfe1e2", "var(--surface-stroke)"],
  ["#1b1b1b", "var(--type-body)"],
  ["#005ea2", "var(--color-link)"],
  ["#1a4480", "var(--color-link-hover)"],
  ["#162e51", "var(--color-link-hover)"],
  ["#54278f", "var(--color-link-visited)"],
  ["#757575", "var(--type-muted)"],
  ["#2491ff", "var(--color-focus-ring)"],
  ["#fff", "var(--surface-page)"],
  ["#ffffff", "var(--surface-page)"],
  ["white", "var(--surface-page)"],
]);

// CSS color keywords as property values (system colors such as CanvasText and
// `transparent` or `currentColor` are fine; they follow the user's or the
// element's own color).
const NAMED_COLOR_VALUE = /(:\s*)(white|black|gr[ae]y|red|green|blue|yellow|orange|purple|pink)\b/g;

const SOURCE = `
@use "uswds-core" with (
  $theme-font-type-sans: "public-sans",
  $theme-show-compile-warnings: false,
  $theme-show-notifications: false,
  $theme-global-link-styles: false,
  $theme-global-paragraph-styles: false,
  $theme-global-content-styles: false,
  $theme-image-path: "../img"
);
@forward "usa-accordion/src/styles";
@forward "usa-banner/src/styles";
@forward "usa-media-block/src/styles";
`;

const svgDataUri = (name) => {
  const file = path.join(uswdsRoot, "dist/img/usa-icons", `${name}.svg`);
  if (!fs.existsSync(file)) {
    throw new Error(`USWDS icon not found: ${file}`);
  }
  const svg = fs.readFileSync(file, "utf-8").replace(/\s+/g, " ").trim();
  return `data:image/svg+xml,${encodeURIComponent(svg)
    .replace(/%20/g, " ")
    .replace(/%3D/g, "=")
    .replace(/%3A/g, ":")
    .replace(/%2F/g, "/")
    .replace(/"/g, "'")}`;
};

export function buildBannerCss() {
  const { css } = sass.compileString(SOURCE, {
    loadPaths: [path.join(uswdsRoot, "packages")],
    style: "expanded",
    quietDeps: true,
  });

  let out = css
    .replace(/@charset "UTF-8";\s*/g, "")
    // USWDS's settings documentation is emitted as comments; none of it is code.
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/rgba\(\s*0\s*,\s*0\s*,\s*0\s*,\s*0\s*\)/g, "transparent")
    .replace(/#[0-9a-fA-F]{3,8}\b/g, (hex) => {
      const token = COLOR_TOKENS.get(hex.toLowerCase());
      if (!token) {
        throw new Error(
          `USWDS banner uses ${hex}, which has no NEXUS token mapping in bin/build-usa-banner.mjs`
        );
      }
      return token;
    })
    .replace(NAMED_COLOR_VALUE, (match, colon, name) => {
      const token = COLOR_TOKENS.get(name.toLowerCase());
      if (!token) {
        throw new Error(
          `USWDS banner uses the color keyword ${name}, which has no NEXUS token mapping in bin/build-usa-banner.mjs`
        );
      }
      return `${colon}${token}`;
    })
    // The theme has no ../img folder: inline the chevron and accordion icons.
    .replace(/url\("\.\.\/img\/usa-icons\/([a-z0-9_]+)\.svg"\)/g, (_, name) => `url("${svgDataUri(name)}")`);

  const leftover = out.match(/rgba?\([^)]*\)|url\("\.\.\/[^"]*"\)|@font-face/g);
  if (leftover) {
    throw new Error(`Unmapped values left in the banner CSS: ${[...new Set(leftover)].join(", ")}`);
  }

  const header = `// Generated by bin/build-usa-banner.mjs from @uswds/uswds ${uswdsVersion}. Do not edit by hand;
// run \`yarn build:usa-banner\` after changing the USWDS version or the script.
// Source: https://designsystem.digital.gov/components/banner/
`;
  return `${header}${out.trim()}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = buildBannerCss();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf-8") : "";
    if (current !== next) {
      console.error("styles/_usa-banner-generated.scss is stale: run yarn build:usa-banner");
      process.exit(1);
    }
    console.log("styles/_usa-banner-generated.scss is up to date");
  } else {
    fs.writeFileSync(OUTPUT, next);
    console.log(`wrote ${path.relative(process.cwd(), OUTPUT)} (${next.length} bytes, USWDS ${uswdsVersion})`);
  }
}
